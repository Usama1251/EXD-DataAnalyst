str = "Usama Mobeen"
print(str[0:5]) #last index will not included

str2 = "Michael Jackson"
print(str2[12:])

#slicing with step

print(str2[0:9:2]) #step 2 means it will take every second character
print(str2[0:9:3]) #step 3 means it will take every third character



